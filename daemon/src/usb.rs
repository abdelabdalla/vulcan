//! Switching USB devices off by deauthorizing them (e.g. a keyboard whose backlight
//! has no software control). The kernel then suspends the device, which cuts it to
//! standby power. Writing the sysfs attributes needs the udev rule from `vulcand udev-rule`.

use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};

use crate::config::UsbConfig;
use crate::protocol::UsbInfo;

const SYSFS: &str = "/sys/bus/usb/devices";
/// Attributes vulcand writes; the udev rule makes these group-writable.
pub const ATTRS: [&str; 3] = ["authorized", "power/control", "power/autosuspend_delay_ms"];

fn read(dir: &Path, attr: &str) -> Option<String> {
    std::fs::read_to_string(dir.join(attr)).ok().map(|s| s.trim().to_string())
}

/// Find the device's sysfs directory by "vendor:product", wherever it's plugged in.
fn find(id: &str) -> Option<PathBuf> {
    let (vendor, product) = id.split_once(':')?;
    std::fs::read_dir(SYSFS).ok()?.flatten().map(|e| e.path()).find(|p| {
        // Interfaces ("1-2:1.0") have no idVendor; only whole devices match.
        read(p, "idVendor").as_deref() == Some(vendor) && read(p, "idProduct").as_deref() == Some(product)
    })
}

pub fn states(devices: &[UsbConfig]) -> Vec<UsbInfo> {
    devices
        .iter()
        .map(|d| {
            let dir = find(&d.id);
            UsbInfo {
                name: d.name.clone(),
                icon: d.icon.clone(),
                present: dir.is_some(),
                on: dir.and_then(|p| read(&p, "authorized")).as_deref() != Some("0"),
            }
        })
        .collect()
}

fn write(dir: &Path, attr: &str, value: &str) -> Result<()> {
    std::fs::write(dir.join(attr), value).map_err(|e| {
        if e.kind() == std::io::ErrorKind::PermissionDenied {
            anyhow::anyhow!(
                "no permission to switch USB devices; run the one-time setup: \
                 vulcand udev-rule | sudo tee /etc/udev/rules.d/70-vulcan-usb.rules, then reload udev (see README)"
            )
        } else {
            anyhow::Error::from(e).context(format!("writing {}", dir.join(attr).display()))
        }
    })
}

/// Connect (`on`), disconnect, or toggle (`None`) the named device.
pub fn set(devices: &[UsbConfig], name: &str, on: Option<bool>) -> Result<String> {
    let dev = devices.iter().find(|d| d.name == name).with_context(|| format!("no USB device named {name:?}"))?;
    let dir = find(&dev.id).with_context(|| format!("{name} ({}) isn't plugged in", dev.id))?;
    let currently_on = read(&dir, "authorized").as_deref() != Some("0");
    let on = on.unwrap_or(!currently_on);
    if on {
        write(&dir, "authorized", "1")?;
        write(&dir, "power/control", "on")?;
        write(&dir, "power/autosuspend_delay_ms", "2000")?;
        Ok(format!("{name} connected"))
    } else {
        // Suspend as soon as it's unbound, so it drops to standby power straight away.
        write(&dir, "power/autosuspend_delay_ms", "0")?;
        write(&dir, "power/control", "auto")?;
        write(&dir, "authorized", "0")?;
        Ok(format!("{name} disconnected"))
    }
}

/// udev rule giving `group` write access to the attributes above, for each configured device.
pub fn udev_rule(devices: &[UsbConfig], group: &str) -> Result<String> {
    if devices.is_empty() {
        bail!("no [[usb]] devices in config.toml");
    }
    let files = ATTRS.map(|a| format!("/sys%p/{a}")).join(" ");
    let mut out = String::from("# Generated by `vulcand udev-rule`: lets vulcand switch these USB devices off and on.\n");
    for d in devices {
        let (vendor, product) = d.id.split_once(':').with_context(|| format!("bad USB id {:?}, expected vendor:product", d.id))?;
        let valid = |s: &str| s.len() == 4 && s.chars().all(|c| c.is_ascii_hexdigit());
        if !valid(vendor) || !valid(product) {
            bail!("bad USB id {:?}, expected vendor:product like 2516:0011", d.id);
        }
        out.push_str(&format!(
            "# {name}\nACTION==\"add\", SUBSYSTEM==\"usb\", ENV{{DEVTYPE}}==\"usb_device\", ATTR{{idVendor}}==\"{vendor}\", ATTR{{idProduct}}==\"{product}\", RUN+=\"/bin/sh -c 'chgrp {group} {files} && chmod g+w {files}'\"\n",
            name = d.name,
        ));
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn dev(id: &str) -> UsbConfig {
        UsbConfig { name: "Keyboard light".into(), id: id.into(), icon: "keyboard".into() }
    }

    #[test]
    fn rule() {
        let r = udev_rule(&[dev("2516:0011")], "abdel").unwrap();
        assert!(r.contains(r#"ATTR{idVendor}=="2516", ATTR{idProduct}=="0011""#));
        assert!(r.contains("chgrp abdel /sys%p/authorized /sys%p/power/control /sys%p/power/autosuspend_delay_ms"));
        assert!(udev_rule(&[dev("2516-0011")], "abdel").is_err());
        assert!(udev_rule(&[dev("25z6:0011")], "abdel").is_err());
        assert!(udev_rule(&[], "abdel").is_err());
    }

    #[test]
    fn unknown_and_unplugged() {
        assert!(set(&[dev("2516:0011")], "nope", None).is_err());
        let s = states(&[dev("ffff:ffff")]);
        assert!(!s[0].present && s[0].on);
        assert!(set(&[UsbConfig { name: "x".into(), id: "ffff:ffff".into(), icon: "x".into() }], "x", None).is_err());
    }
}
